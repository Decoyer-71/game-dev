namespace Jianghu.Core.Martial
{
    /// <summary>
    /// 상태이상 종류.
    ///
    /// ── 성향별 배정 규칙 (2026-07-28 확정) ──────────────────────────────
    /// 상태이상은 각 성향의 **전투 방식**을 완성한다. 성장곡선 정체성과 같은 방향을 가리킨다:
    ///
    ///   · **사파** → 출혈 · 중독
    ///     지속 피해는 방어를 무시하고 확실히 들어간다 = **보장된 저점**.
    ///     사파의 좁은 피해 편차(±5%)와 같은 성격이다 — 계산이 서는 피해.
    ///
    ///   · **정파** → 기력소실
    ///     상대의 자원을 말려 **평타로 전락시킨다**. 즉시 이득이 아니라 장기전에서 이기는 방식.
    ///     정파의 "느리지만 고점이 높다" 와 맞물린다.
    ///
    ///   · **마도** → 마비 · 경직
    ///     턴을 통째로 뺏는다. 걸리면 압도적이고 안 걸리면 아무것도 아니다.
    ///     마도의 넓은 편차(±35%)와 같은 성격 — 도박이다.
    ///
    /// ⚠ 이건 **관례이지 코드로 강제하는 규칙이 아니다.** 나중에 예외적인 무공
    ///   (예: 정파인데 출혈을 거는 특수 절기)이 필요해질 수 있으므로 데이터 층에서만 지킨다.
    /// ────────────────────────────────────────────────────────────────────
    /// </summary>
    public enum StatusEffectKind
    {
        /// <summary>출혈(出血) — 매 턴 고정 피해. 방어를 무시한다. 중첩되지 않고 갱신된다.</summary>
        Bleed = 0,

        /// <summary>중독(中毒) — 매 턴 피해. 방어를 무시하며 **중첩될수록 강해진다**.</summary>
        Poison = 1,

        /// <summary>기력소실(氣力消失) — 매 턴 기력이 깎인다. 상대를 평타로 몰아넣는다.</summary>
        QiDrain = 2,

        /// <summary>마비(痲痺) — 그 턴 행동 불가. 가장 강력하고 그래서 확률이 낮다.</summary>
        Paralysis = 3,

        /// <summary>경직(硬直) — 명중률이 떨어진다.</summary>
        Stagger = 4,

        /// <summary>
        /// 화상(火傷) — **체증형 지속 피해.** 턴이 갈수록 아파진다(1 → 2 → 3). 방어를 무시한다.
        ///
        /// ⚠⚠ 2026-07-31 신설. 정의서 §3-4 의 염(炎)은 형태소로 **먼저** 들어와 있었고
        ///   엔진에 대응물이 없어 *"기력만 먹고 아무 일도 안 하는 글자"* 였다.
        ///
        /// 모양을 셋 다 다르게 잡은 것이 요점이다 — 출혈은 **즉시 일정**, 중독은 **쌓았다가 빠짐**,
        /// 화상은 **유지될수록 커짐**. 같은 '지속 피해' 라도 플레이어가 다르게 다뤄야 한다.
        /// </summary>
        Burn = 5,

        /// <summary>
        /// 동상(凍傷) — **취약.** 걸린 동안 받는 피해가 늘어난다. 스스로는 피해를 주지 않는다.
        ///
        /// ⚠⚠ 2026-07-31 신설. 빙(氷)을 '속도 저하' 로 만들지 않은 이유가 있다 —
        ///   **속도 축이 아직 엔진에 없다.** 거기에 걸면 이번 작업이 없애려는 문제
        ///   (*"값은 있는데 아무 일도 안 하는 글자"*)를 그대로 재생산한다.
        ///
        /// ⚠ 유일하게 **피해를 주지 않는** 상태이상이다. 혼자서는 아무 일도 못 하고
        ///   뒤따르는 타격이 있어야 값을 한다 — 그게 이 글자의 성격이다.
        /// </summary>
        Frostbite = 6,
    }
}
