namespace Jianghu.Core.Martial
{
    /// <summary>
    /// 무공의 접근성 계층. **이 계층이 곧 성장 곡선이다.**
    ///
    /// 그리고 구상안의 학습경로축을 그대로 구현한다:
    ///   강호무학 = 무소속 / 문파무학 = 소·대문파의 일반 무공 / 전승무학 = 대문파의 상징 무공
    ///
    /// ⚠⚠ **밸런싱 기준이 여기서 갈린다.**
    /// 대문파 무공이 소문파 무공보다 강한 것은 **정상**이다 — 접근성이 그 대가다.
    /// 따라서 "승률 격차 30%p 이하"는 **같은 계층 안에서만** 적용한다.
    /// 계층을 무시하고 전체를 평평하게 맞추면 성장의 의미가 사라진다.
    /// 근거: docs/martial-system-proposal.md §3-1, 그리고 낭만강호가
    ///       "문파 전용무공을 범용 강호무공보다 확실히 강하게" 설계했다는 조사 결과.
    /// </summary>
    public enum SchoolTier
    {
        /// <summary>강호무학 — 문파에 속하지 않은 낭인의 무학. 조건 없이 익힌다.</summary>
        Wanderer = 0,

        /// <summary>소문파 — 낮은 조건으로 입문. 무기 1종, 무공 3개.</summary>
        Minor = 1,

        /// <summary>대문파 — 높은 조건이 필요하다. 무기 2종, 무공 6개.</summary>
        Major = 2,
    }
}
