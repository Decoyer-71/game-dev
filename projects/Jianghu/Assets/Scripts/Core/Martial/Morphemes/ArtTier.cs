namespace Jianghu.Core.Martial.Morphemes
{
    /// <summary>
    /// 무공의 접근성 계층 — 정의서 §5-1 의 다섯 계층.
    ///
    /// ⚠ <see cref="SchoolTier"/> 와 구분한다. 저쪽은 **문파**의 계층(소문파·대문파)이고,
    ///   이쪽은 **무공**의 계층이다. 전승무학과 절대경지는 문파가 아니라 무공에만 있는 층이다.
    ///   그래서 전승무학은 문파명에서 유도할 수 없고(대문파 안에 문파무학과 섞여 있다),
    ///   절대경지는 아예 문파에 속하지 않는다(기연으로만 얻는다).
    ///
    /// 이 계층이 조합 규칙 두 가지를 가른다:
    ///   · **극한경지 형태소**는 <see cref="Legacy"/> 에만 (정의서 §5-2 제약 1)
    ///   · **범위 형태소**는 <see cref="Major"/> 이상에만 (2026-07-30 확정 — 광역은 대문파부터)
    /// </summary>
    public enum ArtTier
    {
        /// <summary>강호무학 — 조건 없음. 성능 형태소 2 + 무기 접미사.</summary>
        Wanderer = 0,

        /// <summary>소문파 — 성능 형태소 3.</summary>
        Minor = 1,

        /// <summary>문파무학(대문파) — 성능 형태소 3~4. **여기부터 광역 공격을 쓸 수 있다.**</summary>
        Major = 2,

        /// <summary>전승무학 — 문파당 1개. 성능 형태소 4. **극한경지 1자를 쓸 수 있는 유일한 계층.**</summary>
        Legacy = 3,

        /// <summary>절대경지 — 기연으로만. 수치가 아니라 규칙을 바꾼다(정의서 §5-3).</summary>
        Absolute = 4,
    }
}
