namespace Jianghu.Core.Martial.Morphemes
{
    /// <summary>
    /// 형태소 카테고리. 정의서 §3 의 소절 하나가 여기 한 값에 대응한다.
    ///
    /// **카테고리는 조합 규칙의 단위다.** 정의서 §2-2 규칙 2 가 "카테고리당 최대 1자" 이므로,
    /// 이 enum 의 구획이 곧 "한 무공에 같이 못 들어가는 글자들" 의 정의가 된다.
    /// 예: 참(斬)과 자(刺)는 둘 다 <see cref="AttackMethod"/> 라 한 무공에 못 들어간다
    ///     (한 초식이 베면서 동시에 찌를 수 없다).
    ///
    /// 순서는 정의서 §3-1 ~ §3-10 을 그대로 따른다. 값을 재배열하지 말 것.
    /// </summary>
    public enum MorphemeCategory
    {
        /// <summary>공격 방식(§3-1) — 베기·찌르기·때리기·던지기. 14자. **공격 무공 필수**.</summary>
        AttackMethod = 0,

        /// <summary>방어(§3-2) — 막기·회피·반격. 11자. **경공 무공 필수**.</summary>
        Defense = 1,

        /// <summary>내공(§3-3) — 양·음·합. 3자. **내공 무공 필수**.</summary>
        Internal = 2,

        /// <summary>
        /// 상태이상(§3-4) — 독·혈·비·염·빙 + **탈·경**. 7자.
        /// ⚠ 정의서 원안은 5자였고 탈(奪 기력소실)·경(硬 경직)은 2026-07-29 추가분이다
        ///   (`docs/martial-art-naming.md` §4). 정의서에 역반영이 필요하다.
        /// </summary>
        Status = 3,

        /// <summary>
        /// 무공형태(§3-5) — 정직·무거움·빠름·기만·변화. 9자. **공격 무공 필수**.
        ///
        /// ⚠⚠ 이 카테고리를 필수로 만든 것이 정의서 §2-2 의 핵심이다. 5종 전부
        /// 페널티 없는 상위호환이 다른 카테고리에 존재하므로(정직 공격+2 ↔ 베기 공격+2),
        /// 선택제로 두면 아무도 고르지 않는다. 필수가 되어야 페널티가
        /// **열등함이 아니라 성격**이 된다.
        /// </summary>
        Form = 4,

        /// <summary>수식(§3-6) — 빠르다·맞히다·밝다·어둡다. 11자.</summary>
        Modifier = 5,

        /// <summary>자연속성(§3-7) — 풍·뇌·수·화·냉. 5자. 꾸밈말이되 수치는 0 이 아니다(+1 수준).</summary>
        Element = 6,

        /// <summary>극한경지(§3-8) — 존·제·마·패·성·선·왕·황·종. 9자. **전승무학 전용 · 무공당 1자**(§5-2).</summary>
        Pinnacle = 7,

        /// <summary>부정(§3-9) — 낙·망·멸·산·소. 5자. 자체 수치는 없고 뒤에 오는 무학분류에 상성을 만든다(§4).</summary>
        Negation = 8,

        /// <summary>무학분류(§3-10) — 일·월·혼. 3자. 태그일 뿐 자체 수치가 없다.</summary>
        Tag = 9,

        /// <summary>
        /// 배경어(背景語) — **정의서에 없는 카테고리다.** 2026-07-29 설계 결정 A 로 신설했다.
        ///
        /// 수치가 0 인 어감용 글자다. 천(天)처럼 의미상 무공명에 들어가지만 성능축이 없는 글자를 담는다.
        /// 근거: 정의서 §3-1 이 찌르기 후보 穿 을 제외하며 *"사용례 창천낙월의 천(天)과 겹친다"* 고 적었다.
        /// 즉 정의서는 **수치 없는 글자가 무공명에 들어간다는 것을 이미 전제하고** 다른 형태소를 배제했다.
        ///
        /// ⚠⚠ 세 가지가 다른 카테고리와 다르다:
        ///   1. 수치가 0 이다 (성능 기여 없음)
        ///   2. 기력 소모 글자 수에서 빠진다 (비용 기여 없음 · 결정 B)
        ///   3. §2-2 의 "나머지 카테고리 중 최대 N" 계산에 들어가지 않는다
        /// 즉 **성능도 비용도 0 인 순수 중립 글자**다. 그래서 규제가 없으면
        /// "공짜로 이름을 길게 만드는 장치" 가 된다. 규제 R1~R4 는 <see cref="MorphemeDictionary"/> 참조.
        ///
        /// 대가는 §2-2 규칙 1 이 자동으로 물린다 — "본체 4자 이내" 가 배경어를 **포함해서** 세므로,
        /// 배경어 1자는 성능 슬롯 1개를 포기하는 것이다.
        /// </summary>
        Background = 10,

        /// <summary>
        /// 범위(§3-12) — 다·군·전·만. 4자. **정의서에 없던 카테고리로 2026-07-30 신설**했다.
        ///
        /// **1인 이상의 적을 동시에 때리는 개념**이며, 대상이 늘어나는 만큼 대가를 치른다:
        ///   · 다(多)·군(群)·전(全) — **공격 위력을 판다** (−1 / −2 / −3)
        ///   · 만(萬) — 위력은 유지하되 **기력을 폭증**시킨다 (소모 3배)
        ///
        /// 대가가 없으면 다대다 전투가 생기는 순간 **모든 무공이 광역이 된다.** 그래서 대가가 설계의 본체다.
        ///
        /// ⚠ **공격 무공 전용 · <see cref="ArtTier.Major"/> 이상 전용**이다. 광역은 대문파 무공부터다.
        /// ⚠⚠ 전투 엔진이 아직 1대1이라 **정의됐지만 동작하지 않는다** — <see cref="AttackScope"/> 참조.
        /// </summary>
        Scope = 11,
    }
}
