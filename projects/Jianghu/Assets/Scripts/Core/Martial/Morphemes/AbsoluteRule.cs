namespace Jianghu.Core.Martial.Morphemes
{
    /// <summary>
    /// **절대경지 규칙(§5-3)** — 수치가 아니라 전투 규칙 자체를 바꾸는 효과.
    ///
    /// 정의서 §5-3 이 *"⚠ 수치로 강하게 만들지 않는다. 전승무학을 압도하면 문파 성장 경로가 통째로
    /// 무의미해진다"* 고 못박고 **대신 규칙을 바꾸는** 쪽을 택했다. 그래서 이 넷은
    /// <see cref="ArtStatDelta"/> 에 들어가지 않는다.
    ///
    /// ⚠⚠ **`ArtStatDelta` 에 넣을 수 없는 이유가 구조적이다.** 델타는 22축이 전부 `double` 이고
    ///   무공을 여럿 배우면 **합산**된다(<see cref="ArtStatDelta.op_Addition"/>). 불리언을 억지로
    ///   숫자로 담으면(`statusImmune: 1`) 두 무공을 배웠을 때 2 가 되어 *"면역이 두 겹"* 이라는
    ///   의미 없는 값이 생긴다. 그래서 **<see cref="Combat.Combatant"/> 에서 `any` 로 접는다.**
    ///
    /// 각 규칙은 대형세력 한 곳이 최고 공헌 보상으로 준다(§5-5-c · 배정은 정의서 §5-5-c 표).
    /// </summary>
    public enum AbsoluteRule
    {
        /// <summary>규칙 형태소가 없다. 절대경지가 아닌 모든 무공.</summary>
        None = 0,

        /// <summary>
        /// **면(免) — 모든 상태이상 면역.** 무림맹.
        ///
        /// 상태이상은 사파(출혈·중독)·마도(마비·경직)의 무기다(§6-5). 면역은 그 둘을 정면으로 무력화한다.
        /// ⚠ **부여 단계에서 막는다.** 이미 걸린 것을 지우는 것이 아니라 안 걸리게 하는 것이 "면역" 이다.
        /// </summary>
        StatusImmunity = 1,

        /// <summary>
        /// **무(無) — 기력을 소모하지 않음.** 천마신교.
        ///
        /// ⚠⚠ **지금 이 규칙은 효과가 0 이다.** 평타 전락률이 전 무공·전 경지 **0.0%** 라 아무도 기력이
        ///   마르지 않으므로 소모를 0 으로 만들어도 바뀌는 것이 없다(HANDOFF §4-2-d). 극한경지 선(仙)과
        ///   권(拳)의 기력소모 −100% 가 같은 이유로 죽어 있다.
        ///   → **기력 축 제로섬(§4-2-O)이 풀려야 이 규칙이 산다.** 측정 블록은 그때까지 **판정불가**로 낸다.
        /// </summary>
        NoQiCost = 2,

        /// <summary>
        /// **쌍(雙) — 한 턴에 2회 행동.** 사도련.
        ///
        /// ⚠ 속공(속도 차 × 6% · 상한 50%)과 **겹치지 않는다.** 확정 1회를 쓴 턴에는 속공 판정을
        ///   건너뛴다 — 겹치면 한 턴에 3회가 되어 "2회 행동" 이라는 이름이 거짓말이 된다.
        /// ⚠⚠ **기력 소모도 2배가 된다.** 행동마다 <c>EffectiveQiCost</c> 가 다시 차감되기 때문이다.
        ///   기력 축이 죽은 지금은 무해하지만, 축이 살아나면 **보유자가 스스로 말라붙는다.** 그때 재조정 대상.
        /// </summary>
        DoubleAction = 3,

        /// <summary>
        /// **통(統) — 모든 분류에 상성 +2, 상대 상성 무효.** 제천성.
        ///
        /// 제천성은 정·사·마를 전부 배우는 유일한 곳이다(§5-5-b, 성향 배타의 유일한 예외).
        /// *"모든 것에 강하고 아무에게도 안 눌린다"* 가 그 정체성의 기계적 번역이다.
        ///
        /// ⚠⚠ **양방향이다.** 공격할 때 분류 무관 +2 **그리고** 피격당할 때 상대의 상성을 0 으로 만든다.
        ///   한쪽만 걸면 *"상대 상성 무효"* 라는 이름이 실현되지 않는다.
        /// ⚠ 양쪽이 다 보유하면 서로 무효화되어 **대칭**이 된다.
        /// </summary>
        CounterSupremacy = 4,
    }
}
