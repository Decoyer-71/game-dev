namespace Jianghu.Core.Martial.Morphemes
{
    /// <summary>
    /// 무학분류(武學分類) — 정의서 §3-10. 일(日)·월(月)·혼(混) 세 글자가 붙이는 태그다.
    ///
    /// **자체 수치가 없다.** 이 태그는 상성 규칙(§4)에서만 일한다 —
    /// 부정 한자(낙·망·멸·산·소) **바로 뒤에** 무학분류 한자가 오면 그 분류에 상성 +1 이 된다.
    /// 예: `낙월` = 달을 떨어뜨린다 → 음기무학에 상성 +1.
    ///
    /// ⚠⚠ **인접 조건**이 핵심이다. 부정 한자만 있고 대상이 없으면(`낙성검`) 상성이 생기지 않는다.
    ///   정의서가 이렇게 정한 이유는 *"이름의 의미와 기계 규칙이 정확히 일치"* 하게 하려는 것이다.
    ///   무엇을 부정하는지가 이름에 명시돼야만 상성이 생긴다.
    /// </summary>
    public enum ArtLineage
    {
        /// <summary>분류 태그 없음. 무학분류 형태소가 아닌 대부분의 글자.</summary>
        None = 0,

        /// <summary>양기무학(陽氣武學) — 일(日).</summary>
        Yang = 1,

        /// <summary>음기무학(陰氣武學) — 월(月).</summary>
        Yin = 2,

        /// <summary>혼합무학(混合武學) — 혼(混).</summary>
        Mixed = 3,
    }
}
