namespace Jianghu.Core.Martial.Morphemes
{
    /// <summary>
    /// 초식이 한 번에 때리는 대상의 수 — 정의서 §3-12 범위(範圍) 카테고리가 정한다.
    ///
    /// ⚠⚠ **`MartialArt.HitCount`(타격 횟수)와 다른 축이다.** 헷갈리면 밸런스를 두 번 건드리게 된다:
    ///   · **타격 횟수** — **한 대상**을 여러 번 때린다. 정의서 §6-3 의 문파 가중치('매우'/'극히')가 올린다
    ///   · **범위(이 enum)** — **여러 대상**을 한 번씩 때린다. 무공명의 범위 형태소가 정한다
    ///
    /// ⚠⚠ **2026-07-30 현재 전투 엔진이 이 값을 읽지 않는다.**
    ///   <c>CombatResolver.Resolve(attacker, defender, …)</c> 는 **1대1 전용**이고 다수 전투를 표현할
    ///   자료구조가 없다. 즉 범위 형태소는 **정의됐지만 아직 동작하지 않는다.**
    ///   다대다 전투는 Phase 3(비무대회·문파전)과 함께 붙인다.
    ///
    ///   → **그때까지 이 형태소를 승률표로 판정하지 말 것.** 설계안 §5-4 민감도표는 1대1 승률로 재는데,
    ///     범위 형태소는 거기서 **승률 50% = "무의미한 형태소"** 로 찍힌다. 미구현일 뿐인데
    ///     수치를 올리라는 잘못된 신호를 준다. 이 함정을 모르면 처음부터 다시 조사하게 된다.
    /// </summary>
    public enum AttackScope
    {
        /// <summary>단일 대상. 범위 형태소가 없는 대부분의 무공.</summary>
        Single = 0,

        /// <summary>2인 — 다(多).</summary>
        Two = 1,

        /// <summary>3인 — 군(群).</summary>
        Three = 2,

        /// <summary>전원 — 전(全) · 만(萬).</summary>
        All = 3,
    }
}
